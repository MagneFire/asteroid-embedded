static void test_real(const char *image, const char *ref)
{
	disk_fd = open(image, O_RDONLY);
	if (disk_fd < 0) {
		printf("squashfs_test: %s not found, skipping the real image\n", image);
		return;
	}
	struct stat sb;
	fstat(disk_fd, &sb);
	disk_bytes = (uint64_t)sb.st_size;
	int r = squashfs_open_lba(&fs, "system", 0, (uint32_t)(disk_bytes / EMMC_BLOCK));
	CHECK(r == 0);
	if (r) {
		fprintf(stderr, "open: %s\n", squashfs_strerror(r));
		return;
	}
	printf("squashfs_test: opened %s: block size %u, %u inodes, %u fragments\n", image, fs.bs, fs.inodes, fs.fragments);
	static uint8_t buf[20 << 20];
	for (size_t i = 0; named[i]; i++) {
		char rp[4096];
		snprintf(rp, sizeof rp, "%s%s", ref, named[i]);
		size_t rsize;
		uint8_t *rb = slurp(rp, &rsize);
		CHECK(rb);
		if (!rb) {
			fprintf(stderr, "  no reference for %s\n", named[i]);
			continue;
		}
		int n = squashfs_read_file(&fs, named[i], buf, sizeof buf);
		CHECK(n == (int)rsize && !memcmp(buf, rb, rsize));
		if (n != (int)rsize)
			fprintf(stderr, "  %s: %d (%s)\n", named[i], n, squashfs_strerror(n));
		free(rb);
	}
	struct squashfs_inode in;
	CHECK(squashfs_lookup(&fs, "/etc/firmware/nope.bin", &in) < 0);
	CHECK(squashfs_lookup(&fs, "/etc/firmware/TIInit_11.8.32.bts/x", &in) < 0);
	CHECK(squashfs_lookup(&fs, "/lib/libm.so", &in) == 0 && in.size == 132820 && in.frag == 0xffffffffu);
	struct squashfs_inode tb;
	CHECK(squashfs_lookup(&fs, "/app/Bluetooth/lib/arm/libbluetooth_jni.so", &in) == 0);
	CHECK(squashfs_lookup(&fs, "/lib/libbluetooth_jni.so", &tb) == 0 && in.ref == tb.ref && in.size == tb.size);
	CHECK(squashfs_lookup(&fs, "/bin/top", &in) == 0 && squashfs_lookup(&fs, "/bin/toolbox", &tb) == 0);
	CHECK(in.size == tb.size && in.ref == tb.ref);
	struct stats st = { 0 };
	walk_tree(ref, &st, NULL, 0);
	nftw(ref, count_fn, 32, FTW_PHYS);
	printf("squashfs_test: tree walk: %u dirs, %u regular files, %u symlinks; %u files (%llu bytes) identical to the reference, "
	       "%u skipped (not in the reference), %u symlinks followed and checked, %u mismatches, %u read errors\n",
	       st.dirs, st.files, st.symlinks, st.compared, (unsigned long long)st.bytes, st.skipped, st.links_followed,
	       st.mismatches, st.errors);
	printf("squashfs_test: coverage: %u fragment-only files, %u multi-block files with a fragment tail, "
	       "%u exact multiples of the block size, %u empty files; %u regular files in the reference tree\n",
	       st.fragment_only, st.fragment_tail, st.exact_multiple, st.empty, ref_files);
	CHECK(st.mismatches == 0 && st.errors == 0 && st.compared + st.skipped == st.files);
	close(disk_fd);
	disk_fd = -1;
}

int main(int argc, char **argv)
{
	test_inflate();
	test_small(argc > 3 ? argv[3] : "tests/data/small.squashfs");
	if (argc > 2)
		test_real(argv[1], argv[2]);
	else
		printf("squashfs_test: no real image given, skipping it\n");
	if (failures)
		return 1;
	printf("squashfs_test: ok\n");
	return 0;
}
