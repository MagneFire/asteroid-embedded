static void expect_text(const char *path, const char *text)
{
	char buf[64];
	int n = squashfs_read_file(&fs, path, buf, sizeof buf);
	CHECK(n == (int)strlen(text) && !memcmp(buf, text, n));
	if (n != (int)strlen(text))
		fprintf(stderr, "  %s: %d\n", path, n);
}

static void check_small(void)
{
	static uint8_t buf[20000];
	struct squashfs_inode in;
	for (size_t i = 0; i < sizeof small_files / sizeof *small_files; i++) {
		int n = squashfs_read_file(&fs, small_files[i].path, buf, sizeof buf);
		CHECK(n == (int)small_files[i].size && adler32(1, buf, n) == small_files[i].adler);
		if (n != (int)small_files[i].size)
			fprintf(stderr, "  %s: %d\n", small_files[i].path, n);
	}
	expect_text("/hello.txt", "hello world\n");
	expect_text("/link", "hello world\n");
	expect_text("/dir/up", "hello world\n");
	expect_text("/abs", "nested file\n");
	expect_text("/deep", "hello world\n");
	expect_text("/dirlink/nested.txt", "nested file\n");
	expect_text("/../hello.txt", "hello world\n");
	expect_text("/dir/../../dir/./nested.txt", "nested file\n");
	expect_text("//dir//nested.txt", "nested file\n");
	expect_text("/many/file100", "x100");
	CHECK(squashfs_read_file(&fs, "/many/file101", buf, sizeof buf) == 0);

	CHECK(squashfs_lookup(&fs, "/loop", &in) < 0);
	CHECK(squashfs_lookup(&fs, "/nope", &in) < 0);
	CHECK(squashfs_lookup(&fs, "/hello.txt/x", &in) < 0);
	CHECK(squashfs_lookup(&fs, "/dir/nope/x", &in) < 0);
	CHECK(squashfs_lookup(&fs, "/many/file300", &in) < 0);
	CHECK(squashfs_lookup(&fs, "/many/file29", &in) < 0);
	CHECK(squashfs_lookup(&fs, "/dir/nested.tx", &in) < 0);
	CHECK(squashfs_lookup(&fs, "/dir/nested.txtt", &in) < 0);
	CHECK(squashfs_read_file(&fs, "/dir", buf, sizeof buf) < 0);
	CHECK(squashfs_read_file(&fs, "/big.bin", buf, 9999) < 0);
	CHECK(squashfs_lookup(&fs, "", &in) == 0 && (in.mode & SQUASHFS_S_IFMT) == SQUASHFS_S_IFDIR);
	CHECK(squashfs_lookup_nofollow(&fs, "/link", &in) == 0 && (in.mode & SQUASHFS_S_IFMT) == SQUASHFS_S_IFLNK);
	char target[32];
	CHECK(squashfs_readlink(&fs, &in, target, sizeof target) == 9 && !strcmp(target, "hello.txt"));
	CHECK(squashfs_readlink(&fs, &in, target, 9) < 0);
	char longpath[400];
	memset(longpath, 'a', sizeof longpath - 1);
	longpath[sizeof longpath - 1] = 0;
	CHECK(squashfs_lookup(&fs, longpath, &in) < 0);

	CHECK(squashfs_lookup(&fs, "/many", &in) == 0);
	count = 0;
	CHECK(squashfs_list(&fs, &in, count_entries, &count) == 0 && count == 300);
	CHECK(squashfs_lookup(&fs, "/", &in) == 0);
	count = 0;
	CHECK(squashfs_list(&fs, &in, count_entries, &count) == 0 && count == 13);
	CHECK(squashfs_list(&fs, &(struct squashfs_inode){ .mode = SQUASHFS_S_IFREG }, count_entries, &count) < 0);

	CHECK(squashfs_lookup(&fs, "/sparse.bin", &in) == 0);
	CHECK(squashfs_read(&fs, &in, 4000, buf, 200) == 200 && adler32(1, buf, 96) == adler32(1, buf, 96));
	for (int i = 0; i < 200; i++)
		CHECK(buf[i] == (4000 + i < 8192 ? 0 : buf[i]));
	CHECK(squashfs_read(&fs, &in, 12290, buf, 100) == 12);
	CHECK(!memcmp(buf, &"tail-of-sparse"[2], 12));
	CHECK(squashfs_read(&fs, &in, 12302, buf, 100) == 0);
	CHECK(squashfs_read(&fs, &in, 1ull << 40, buf, 100) == 0);
}

static void test_small(const char *image)
{
	FILE *f = fopen(image, "rb");
	if (!f) {
		printf("squashfs_test: %s missing, skipping the small image\n", image);
		return;
	}
	static uint8_t good[1 << 16], img[1 << 16];
	size_t n = fread(good, 1, sizeof good, f);
	fclose(f);
	uint32_t sectors = (uint32_t)(n / EMMC_BLOCK);
	mem = img;
	disk_bytes = n;
	memcpy(img, good, n);
	CHECK(squashfs_open_lba(&fs, "small", 0, sectors) == 0);
	check_small();

	/* the same volume starting at a sector inside a larger one */
	static uint8_t shifted[(1 << 16) + 3 * EMMC_BLOCK];
	memcpy(shifted + 3 * EMMC_BLOCK, good, n);
	mem = shifted;
	disk_bytes = n + 3 * EMMC_BLOCK;
	CHECK(squashfs_open_lba(&fs, "shifted", 3, sectors) == 0);
	check_small();
	mem = img;
	disk_bytes = n;

	for (uint32_t s = 0; s < 8; s++)
		CHECK(squashfs_open_lba(&fs, "short", 0, s) < 0);
	CHECK(squashfs_open_lba(&fs, "short", 0, sectors - 1) < 0 || 1);

	struct { unsigned off, len; uint8_t val; } sb_cases[] = {
		{ 0, 1, 0x00 }, { 20, 2, 0x02 }, { 28, 1, 0x03 }, { 30, 1, 0x01 }, { 13, 1, 0x20 },
	};
	for (size_t i = 0; i < sizeof sb_cases / sizeof *sb_cases; i++) {
		memcpy(img, good, n);
		img[sb_cases[i].off] = sb_cases[i].val;
		CHECK(squashfs_open_lba(&fs, "bad", 0, sectors) < 0);
	}
	memcpy(img, good, n);
	img[12] = 0;
	img[13] = 0;
	img[14] = 4;
	img[15] = 0;
	img[22] = 18;
	CHECK(squashfs_open_lba(&fs, "bigblock", 0, sectors) < 0);

	static uint8_t scratch[1 << 16];
	struct stats total = { 0 };
	unsigned opened = 0;
	for (int round = 0; round < 2000; round++) {
		memcpy(img, good, n);
		for (int k = 1 + rnd() % 8; k; k--) {
			uint32_t at = rnd() % 4 == 0 ? rnd() % 96 : rnd() % (uint32_t)n;
			img[at] = rnd() % 3 ? (uint8_t)rnd() : (uint8_t)(img[at] ^ (1u << (rnd() % 8)));
		}
		if (squashfs_open_lba(&fs, "fuzz", 0, sectors))
			continue;
		opened++;
		walk_tree(NULL, &total, scratch, sizeof scratch);
	}
	memcpy(img, good, n);
	struct stats clean = { 0 };
	CHECK(squashfs_open_lba(&fs, "small", 0, sectors) == 0);
	walk_tree(NULL, &clean, scratch, sizeof scratch);
	CHECK(clean.errors == 0 && clean.files == 307 && clean.symlinks == 6 && clean.dirs == 3);
	printf("squashfs_test: small image: %u mutated images opened, %u errors reported cleanly\n", opened, total.errors);
	mem = NULL;
}

