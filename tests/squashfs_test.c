static void check_vec(const uint8_t *z, size_t n, const uint8_t *exp, size_t elen)
{
	uint8_t out[4000];
	size_t got = 0;
	CHECK(zlib_inflate(z, n, out, sizeof out, &got) == 0);
	CHECK(got == elen && !memcmp(out, exp, elen));
	CHECK(zlib_inflate(z, n, out, elen, &got) == 0 && got == elen);
	if (elen)
		CHECK(zlib_inflate(z, n, out, elen - 1, &got) == INFLATE_E_OVERFLOW);
	CHECK(zlib_inflate(z, n, out, 0, &got) == INFLATE_E_OVERFLOW || !elen);

	uint8_t bad[1024];
	memcpy(bad, z, n);
	bad[n - 1] ^= 1;
	CHECK(zlib_inflate(bad, n, out, sizeof out, &got) == INFLATE_E_ADLER);
	bad[n - 1] ^= 1;
	for (size_t cut = 0; cut < n; cut++)
		CHECK(zlib_inflate(z, cut, out, sizeof out, &got) < 0);
	bad[0] ^= 0x01;
	CHECK(zlib_inflate(bad, n, out, sizeof out, &got) == INFLATE_E_HEADER);
	bad[0] ^= 0x01;
	bad[1] ^= 0x20;
	CHECK(zlib_inflate(bad, n, out, sizeof out, &got) == INFLATE_E_HEADER);
	for (int round = 0; round < 3000; round++) {
		memcpy(bad, z, n);
		for (int k = 1 + rnd() % 3; k; k--)
			bad[rnd() % n] ^= (uint8_t)(1u << (rnd() % 8));
		if (!zlib_inflate(bad, n, out, sizeof out, &got))
			CHECK(got <= sizeof out);
	}
}

