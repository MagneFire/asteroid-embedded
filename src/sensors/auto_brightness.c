static int32_t limit(int profile, int step)
{
	return step < 0 ? 0 : step < STEPS ? limits[profile][step] : INT32_MAX;
}

static int32_t min32(int32_t a, int32_t b)
{
	return a < b ? a : b;
}

void auto_brightness_reset(struct auto_brightness *a)
{
	a->n = 0;
}

void auto_brightness_add(struct auto_brightness *a, int32_t lux)
{
	int32_t sorted[AUTO_BRIGHTNESS_WINDOW];
	if (a->n == AUTO_BRIGHTNESS_WINDOW) {
		for (unsigned i = 1; i < a->n; i++)
			a->window[i - 1] = a->window[i];
		a->n--;
	}
	a->window[a->n++] = lux;
	for (unsigned i = 0; i < a->n; i++) {
		unsigned j = i;
		for (; j && sorted[j - 1] > a->window[i]; j--)
			sorted[j] = sorted[j - 1];
		sorted[j] = a->window[i];
	}
	a->lux = sorted[a->n / 2];
	a->have_lux = true;
}

int auto_brightness_percent(struct auto_brightness *a, int setting)
{
	if (!a->have_lux)
		return setting;
	int profile = ((setting - 1) * (PROFILES - 1) + 49) / 99;
	profile = profile < 0 ? 0 : profile >= PROFILES ? PROFILES - 1 : profile;
	if (a->have_level && a->profile == profile && a->lo <= a->lux && a->lux <= a->hi)
		return a->level;
	int step = 0;
	while (step < STEPS && a->lux >= limits[profile][step])
		step++;
	int32_t below2 = limit(profile, step - 2), below = limit(profile, step - 1), above = limit(profile, step);
	a->have_level = true;
	a->profile = profile;
	a->level = step < STEPS ? levels[profile][step] : 100;
	a->lo = below - min32(below - below2, above - below) / 10;
	a->hi = above;
	return a->level;
}
