#!/usr/bin/env python3
"""Writes src/display/flatmesh_mcu_data.h from src/display/flatmesh_geometry.h: the FlatMesh as
flatmesh.c draws it at time 0 on a rectangular panel at view scale 1.1, as shared points in units
of 1/8192 of the screen and triangles of three of them, top first, each with its share of the centre
colour. Triangles of the outer colour alone, and those off the screen even when the mesh is moved
by 5 % of it, are left out.
usage: tools/ui-mcu/flatmesh.py"""
import os
import re
import struct

SCALE, VIEW, MOVE, UNIT = 1.45, 1.1, 0.05, 8192

root = os.path.join(os.path.dirname(__file__), "..", "..")
src = open(os.path.join(root, "src/display/flatmesh_geometry.h")).read()


def table(name):
    body = re.search(name + r"\[[^]]*\](?:\[\d+\])?\s*=\s*\{(.*?)\n\};", src, re.S).group(1)
    return body


def f32(x):
    return struct.unpack("f", struct.pack("f", x))[0]


vertices = [tuple(f32(float(n)) for n in re.findall(r"[-0-9.e]+(?=f)", row))
            for row in re.findall(r"\{([^}]*)\}", table("flatmesh_vertices"))]
indices = [int(n) for n in re.findall(r"\d+", table("flatmesh_indices"))]
shifts = [tuple(f32(float(n)) for n in re.findall(r"[-0-9.e]+(?=f)", row))
          for row in re.findall(r"\{([^}]*)\}", table("flatmesh_shifts"))]

points, point_of, triangles = [], {}, []
for t in range(len(indices) // 3):
    corner = []
    for i in indices[3 * t:3 * t + 3]:
        v = vertices[i]
        h = int(f32(v[0] * 100.0)) + int(f32(v[1] * 100.0))
        s = shifts[h % len(shifts)]
        p = tuple(round((0.5 + (v[k] + s[k]) * SCALE * VIEW) * UNIT) for k in range(2))
        if p not in point_of:
            point_of[p] = None
        corner.append(p)
    m = vertices[indices[3 * t]][2]
    xs, ys = [p[0] for p in corner], [p[1] for p in corner]
    lo, hi = -MOVE * UNIT, (1 + MOVE) * UNIT
    if m >= 1.0 or max(xs) < lo or min(xs) > hi or max(ys) < lo or min(ys) > hi:
        continue
    corner.sort(key=lambda p: (p[1], p[0]))
    triangles.append((corner, round((1 - m) * 255)))

triangles.sort(key=lambda t: t[0][0][1])
for corner, _ in triangles:
    for p in corner:
        if point_of[p] is None:
            point_of[p] = len(points)
            points.append(p)
assert len(points) < 256

# The most triangles a line crosses, moved up or down by up to 5 %.
most = 0
for y in range(-int(MOVE * UNIT), int((1 + MOVE) * UNIT), 8):
    most = max(most, sum(1 for c, _ in triangles if c[0][1] <= y < c[2][1]))

out = ["/* Generated by tools/ui-mcu/flatmesh.py from flatmesh_geometry.h: do not edit. */",
       "#define FLATMESH_MCU_POINTS %d" % len(points),
       "#define FLATMESH_MCU_TRIANGLES %d" % len(triangles),
       "#define FLATMESH_MCU_CROSSING %d" % most,
       "",
       "static const int16_t flatmesh_mcu_points[FLATMESH_MCU_POINTS][2] = {"]
for i in range(0, len(points), 6):
    out.append("\t" + " ".join("{ %d, %d }," % p for p in points[i:i + 6]))
out += ["};", "", "/* Corners, top first, and the share of the centre colour out of 255. */",
        "static const uint8_t flatmesh_mcu_triangles[FLATMESH_MCU_TRIANGLES][4] = {"]
for i in range(0, len(triangles), 6):
    out.append("\t" + " ".join("{ %d, %d, %d, %d }," % (*(point_of[p] for p in c), s)
                               for c, s in triangles[i:i + 6]))
out.append("};")
open(os.path.join(root, "src/display/flatmesh_mcu_data.h"), "w").write("\n".join(out) + "\n")
print(f"{len(points)} points, {len(triangles)} triangles, at most {most} on a line")
